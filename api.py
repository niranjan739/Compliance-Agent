"""HTTP API for viewing generated compliance reports."""

import json
from pathlib import Path

from fastapi import FastAPI, HTTPException


app = FastAPI(
    title="Compliance Agent API",
    description="Read compliance analysis results generated by main.py.",
    version="1.0.0",
)

REPORT_FILE = Path(__file__).resolve().parent / "compliance_report.json"


def load_reports():
    """Load the latest generated report or return a meaningful API error."""
    if not REPORT_FILE.is_file():
        raise HTTPException(
            status_code=404,
            detail="Compliance report not found. Run main.py before requesting results.",
        )

    try:
        with REPORT_FILE.open("r", encoding="utf-8") as report_file:
            reports = json.load(report_file)
    except json.JSONDecodeError as error:
        raise HTTPException(
            status_code=500,
            detail="Compliance report contains invalid JSON.",
        ) from error

    if not isinstance(reports, list):
        raise HTTPException(
            status_code=500,
            detail="Compliance report must contain a JSON list of results.",
        )

    return reports


@app.get("/health")
def health_check():
    """Confirm that the API is running."""
    return {"status": "ok"}


@app.get("/compliance-reports")
def get_compliance_reports():
    """Return every result in compliance_report.json."""
    return load_reports()


@app.get("/compliance-reports/{email_id}")
def get_compliance_report(email_id: int):
    """Return the result for one numeric email identifier, for example 1."""
    report = next(
        (item for item in load_reports() if item.get("emailId") == email_id),
        None,
    )
    if report is None:
        raise HTTPException(
            status_code=404,
            detail=f"Report for {email_id} was not found.",
        )

    return report
